import { startServer } from '../index.js';
import WebSocket from 'ws';
import { PRESETS } from '../data/presets.js';
process.env.DEV_AUTH='1'; process.env.DEV_MEMORY_DB='1';
const app = await startServer({ port: 0, log:{info(){},warn(){},error:console.error} });
const db = app.db;
await db.raw.teams.upsert({id:'t1',name:'가',color:'#ff0000'}); await db.raw.teams.upsert({id:'t2',name:'나',color:'#0000ff'});
await db.raw.profiles.upsert({id:'dev-m1',login_id:'m1',nickname:'m1',role:'mechanic',team_id:'t1'});
await db.raw.profiles.upsert({id:'dev-m2',login_id:'m2',nickname:'m2',role:'mechanic',team_id:'t2'});
const p=PRESETS[0];
await db.raw.robots.upsert({id:'r1',owner:'dev-m1',name:p.name,design:p,tactics:p.tactics});
await db.raw.robots.upsert({id:'r2',owner:'dev-m2',name:p.name,design:p,tactics:p.tactics});
const open=(tok)=>new Promise(res=>{const ws=new WebSocket(`ws://localhost:${app.port}/ws`);ws.on('open',()=>{ws.send(JSON.stringify({type:'auth',token:tok}));setTimeout(()=>res(ws),100)})});
let id=0; const cmd=(ws,op,a={})=>new Promise(res=>{const i=++id;const h=d=>{const m=JSON.parse(d);if(m.type==='res'&&m.id===i){ws.off('message',h);res(m)}};ws.on('message',h);ws.send(JSON.stringify({type:'cmd',...a,rid:i,op}))});
const cm=await open('dev:commander:boss:지휘'); const m1=await open('dev:mechanic:m1:a'); const m2=await open('dev:mechanic:m2:b');
const show=(n,r)=>console.log(n,r.ok,r.ok?JSON.stringify(r.data).slice(0,110):r.error);
show('get v0',await cmd(m1,'balance.get'));
show('mech save',await cmd(m1,'balance.save',{data:{constants:{'spirit.start':70}},baseVersion:0}));
show('bad save',await cmd(cm,'balance.save',{data:{constants:{'tactics.rangeBand.near':30,'tactics.rangeBand.mid':20}},baseVersion:0}));
show('save v1',await cmd(cm,'balance.save',{data:{constants:{'spirit.start':70,'time.matchSeconds':9999}},baseVersion:0,note:'시험'}));
show('conflict',await cmd(cm,'balance.save',{data:{constants:{'spirit.start':80}},baseVersion:0}));
show('nochange',await cmd(cm,'balance.save',{data:{constants:{'spirit.start':70,'time.matchSeconds':600}},baseVersion:1}));
show('get v1',await cmd(m1,'balance.get'));
show('list',await cmd(cm,'balance.list'));
const cr=await cmd(cm,'league.create',{config:{name:'밸',teamSize:1,matchSeconds:45}}); const L=cr.data.id;
console.log('league balance_version',(await db.getLeague(L)).balance_version);
await cmd(cm,'balance.save',{data:{constants:{'spirit.start':90}},baseVersion:1}); // v2 저장 — 리그는 v1 고정
await cmd(m1,'roster.register',{leagueId:L,robotIds:['r1']}); await cmd(m2,'roster.register',{leagueId:L,robotIds:['r2']});
await cmd(cm,'schedule.generate',{leagueId:L});
const mid=(await cmd(cm,'league.view',{leagueId:L})).data.matches[0].id;
await cmd(cm,'match.prepare',{matchId:mid});
const w=app.leagues.runnerOf(mid).match.world;
console.log('match constants: spirit.start',w.constants.spirit.start,'matchSeconds',w.constants.time.matchSeconds,'(기대 70, 45)');
await cmd(cm,'match.abort',{matchId:mid});
await app.stop(); process.exit(0);
